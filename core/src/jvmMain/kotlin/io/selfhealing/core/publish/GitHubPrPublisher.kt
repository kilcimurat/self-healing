internal data class GitHubRepoRef(val host: String, val owner: String, val repo: String)

/** Parses https://host/o/r(.git), git@host:o/r.git and ssh://git@host/o/r.git. */
internal fun parseGitHubRepo(url: String): GitHubRepoRef {
    val u = url.trim()
    val m = Regex("""^(?:[a-zA-Z][a-zA-Z0-9+.-]*://)?(?:[^@/]+@)?([^/:]+)(?::\d+)?[:/]+([^/]+)/([^/]+?)(?:\.git)?/?$""").matchEntire(u)
        ?: throw IllegalArgumentException("Cannot parse GitHub owner/repo from '$url'")
    return GitHubRepoRef(m.groupValues[1], m.groupValues[2], m.groupValues[3])
}

internal fun buildPrTitle(crash: CrashReport): String = "fix(crash): ${crash.title}".take(100)

internal fun buildPrBody(
    crash: CrashReport,
    summary: FixSummary,
    verification: VerificationResult,
    hasScreenshots: Boolean,
): String = buildString {
    appendLine("## Sentry crash")
    crash.permalink?.let { appendLine("- Link: $it") }
    appendLine("- Title: ${crash.title}")
    appendLine("- Platform: ${crash.platform.name.lowercase()}")
    crash.release?.let { appendLine("- Release: $it") }
    crash.level?.let { appendLine("- Level: $it") }
    appendLine()
    appendLine("## Root cause")
    appendLine(summary.rootCause.ifBlank { "_Not provided._" })
    appendLine()
    appendLine("## Fix")
    appendLine(summary.fix.ifBlank { "_Not provided._" })
    appendLine()
    appendLine("## Files changed")
    if (summary.filesChanged.isEmpty()) appendLine("_None reported._") else summary.filesChanged.forEach { appendLine("- `$it`") }
    appendLine()
    appendLine("## Tests added")
    if (summary.testsAdded.isEmpty()) appendLine("_None._") else summary.testsAdded.forEach { appendLine("- `$it`") }
    appendLine()
    appendLine("## Verification")
    appendLine(verification.details.ifBlank { if (verification.success) "App built and launched successfully." else "Verification failed." })
    if (summary.reproSteps.isNotEmpty()) {
        appendLine()
        appendLine("Repro steps:")
        summary.reproSteps.forEachIndexed { i, s -> appendLine("${i + 1}. $s") }
    }
    if (hasScreenshots) {
        appendLine()
        appendLine("Recordings of every platform are in the comment below.")
    }
    appendLine()
    appendLine("<details><summary>Stack trace</summary>")
    appendLine()
    appendLine("```")
    appendLine(crash.stacktrace.trim().take(6000))
    appendLine("```")
    appendLine("</details>")
    appendLine()
    appendLine("---")
    appendLine("Generated by Self-Healing — review before merging.")
}

/** Step label for a screenshot file name like `android-00-release-after-repro.png`. */
private val stepLabels = linkedMapOf(
    "00-release-launch" to "Release build · launch",
    "00-release-after-repro" to "Release build · after repro flow",
    "01-launch" to "Fixed build · launch",
    "02-after-repro" to "Fixed build · after repro flow",
    "02-after-wait" to "Fixed build · after wait",
    "03-after-resume" to "Fixed build · after background → foreground",
)

/** PR comment: the combined crash video when there is one, else screenshots in a step × platform table. */
internal fun buildScreenshotComment(shots: PublishedScreenshots, ref: GitHubRepoRef): String {
    fun url(path: String) = "https://${ref.host}/${ref.owner}/${ref.repo}/blob/${shots.branch}/$path?raw=true"
    val video = shots.paths.firstOrNull { it.endsWith(".mp4") } ?: return buildScreenshotTable(shots, ::url)
    val gif = shots.paths.firstOrNull { it.endsWith(".gif") }
    return buildString {
        appendLine("## Crash video")
        appendLine()
        appendLine("Android on the left, iOS on the right. Top: the released build, recorded until the crash. Bottom: the fixed build running the same flow.")
        appendLine("Every tap of the repro flow is marked with a ring. A shorter clip holds on its last frame.")
        appendLine()
        if (gif != null) appendLine("<a href=\"${url(video)}\"><img src=\"${url(gif)}\" width=\"520\"></a>").also { appendLine() }
        appendLine("▶ [Full-quality video (MP4)](${url(video)})")
        appendLine()
        appendLine("_Hosted on the `${shots.branch}` branch, outside this PR's diff._")
    }
}

private fun buildScreenshotTable(shots: PublishedScreenshots, url: (String) -> String): String = buildString {
    val byFile = shots.paths.associateBy { it.substringAfterLast('/').removeSuffix(".png") }
    val platforms = byFile.keys.map { it.substringBefore('-') }.distinct().sortedBy { if (it == "android") 0 else 1 }
    val steps = (stepLabels.keys + byFile.keys.map { it.substringAfter('-') }).distinct()
        .filter { step -> platforms.any { "$it-$step" in byFile } }
    appendLine("## Screenshots")
    appendLine()
    appendLine("| Step | " + platforms.joinToString(" | ") { if (it == "ios") "iOS" else it.replaceFirstChar(Char::uppercase) } + " |")
    appendLine("|---|" + platforms.joinToString("") { "---|" })
    steps.forEach { step ->
        val cells = platforms.joinToString(" | ") { p -> byFile["$p-$step"]?.let { "<img src=\"${url(it)}\" width=\"240\">" } ?: "—" }
        appendLine("| ${stepLabels[step] ?: step} | $cells |")
    }
    appendLine()
    appendLine("_Hosted on the `${shots.branch}` branch, outside this PR's diff._")
}

class GitHubPrPublisher(private val config: GitHubConfig) : PrPublisher {
    private val json = Json { ignoreUnknownKeys = true; isLenient = true }

    override suspend fun publish(
        repo: RepoConfig,
        prepared: PreparedRepo,
        crash: CrashReport,
        summary: FixSummary,
        verification: VerificationResult,
        screenshots: PublishedScreenshots?,
        log: LineSink,
    ): String {
        val ref = parseGitHubRepo(repo.url)
        val api = "${config.apiUrl.trimEnd('/')}/repos/${ref.owner}/${ref.repo}"
        val client = HttpClient(CIO)
        try {
            suspend fun send(url: String, body: JsonObject): HttpResponse = client.post(url) {
                headers(this)
                setBody(TextContent(body.toString(), ContentType.Application.Json))
            }

            val payload = buildJsonObject {
                put("title", buildPrTitle(crash))
                put("head", prepared.branch)
                put("base", prepared.baseBranch)
                put("body", buildPrBody(crash, summary, verification, !screenshots?.paths.isNullOrEmpty()))
                put("draft", config.draftPr)
            }
            val resp = send("$api/pulls", payload)
            val text = resp.bodyAsText()
            val pr: JsonObject = if (resp.status.isSuccess()) {
                json.parseToJsonElement(text).jsonObject
            } else if (resp.status.value == 422 && text.contains("already exists")) {
                log.line(LogSource.GIT, "PR already exists for ${prepared.branch}; reusing it")
                findExisting(client, api, ref, prepared.branch)
                    ?: error("PR exists but could not be found: $text")
            } else {
                error("Creating PR failed (${resp.status.value}): ${text.take(500)}")
            }
            val number = pr["number"]!!.jsonPrimitive.int
            val url = pr["html_url"]!!.jsonPrimitive.content
            log.line(LogSource.GIT, "Pull request #$number: $url")

            if (config.labels.isNotEmpty()) attempt(log, "labels") {
                send("$api/issues/$number/labels", buildJsonObject { putJsonArray("labels") { config.labels.forEach { add(JsonPrimitive(it)) } } })
            }
            if (screenshots != null && screenshots.paths.isNotEmpty()) attempt(log, "screenshot comment") {
                send("$api/issues/$number/comments", buildJsonObject { put("body", buildScreenshotComment(screenshots, ref)) })
            }
            if (config.reviewers.isNotEmpty()) attempt(log, "reviewers") {
                send("$api/pulls/$number/requested_reviewers", buildJsonObject { putJsonArray("reviewers") { config.reviewers.forEach { add(JsonPrimitive(it)) } } })
            }
            return url
        } finally {
            client.close()
        }
    }

    private fun headers(b: io.ktor.client.request.HttpRequestBuilder) {
        b.header("Authorization", "Bearer ${config.token}")
        b.header("Accept", "application/vnd.github+json")
        b.header("X-GitHub-Api-Version", "2022-11-28")
    }

    private suspend fun findExisting(client: HttpClient, api: String, ref: GitHubRepoRef, branch: String): JsonObject? {
        val resp = client.get("$api/pulls?state=open&head=${ref.owner}:$branch") { headers(this) }
        if (!resp.status.isSuccess()) return null
        return (json.parseToJsonElement(resp.bodyAsText()) as? JsonArray)?.firstOrNull()?.jsonObject
    }

    private suspend fun attempt(log: LineSink, what: String, block: suspend () -> HttpResponse) {
        try {
            val r = block()
            if (!r.status.isSuccess()) log.line(LogSource.GIT, "Setting PR $what failed (${r.status.value}): ${r.bodyAsText().take(200)}")
        } catch (e: Exception) {
            log.line(LogSource.GIT, "Setting PR $what failed: ${e.message}")
        }
    }
}
